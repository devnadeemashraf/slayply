import type { OPTION_LABELS, SectionId } from "./context-answers.js";

/**
 * The questionnaire as plain data: what to ask, how to explain it, and where each answer goes.
 * The zod schema in `context-answers.ts` stays the source of truth for shape and limits; a test
 * checks that this list and the schema cover exactly the same fields.
 */

export type Use =
  /** Becomes a fact the model may cite. */
  | "fact"
  /** Becomes a writing preference. */
  | "pref"
  /** Stays on this device and is never sent. */
  | "local_only";

export type Control =
  | "text"
  | "longtext"
  | "select"
  | "multiselect"
  | "month"
  | "monthOrPresent"
  | "number"
  | "list";

export type QuestionDef = {
  /** Field name inside the section (or inside the entry, for a repeatable section). */
  path: string;
  label: string;
  help: string;
  example?: string;
  control: Control;
  /** For `select` and `multiselect`: which option list to use. */
  options?: keyof typeof OPTION_LABELS;
  /** Needed before this entry can become facts. Does not block saving a draft. */
  required?: boolean;
  /** For `list`: the most items allowed. */
  maxItems?: number;
  /** For `text`, `longtext` and list items: the most characters allowed. */
  maxChars?: number;
  use: Use;
  /** A nested group of questions, for example the three parts of an achievement. */
  group?: { maxItems: number; questions: QuestionDef[] };
};

export type QuestionnaireSection = {
  id: SectionId;
  title: string;
  intro: string;
  /** What happens to this section's answers, in plain words (SPEC section 5). */
  privacy: string;
  repeatable?: { entryLabel: string; maxEntries: number; hint: string };
  questions: QuestionDef[];
};

